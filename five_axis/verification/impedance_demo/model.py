"""Simulation-only MJCF derived from current canonical URDF and CAD audit."""
from pathlib import Path
import json
import sys
import xml.etree.ElementTree as ET
import numpy as np
from scipy.spatial.transform import Rotation

WORKSPACE = Path(__file__).resolve().parents[2]
try:
    import mujoco
except ImportError:
    sys.path.append(str(WORKSPACE.parent / '五轴仿真' / '_sim_deps'))
    import mujoco

URDF = WORKSPACE / 'src/slaihand_description/urdf/slaihand_four_axis.urdf'
MASS = WORKSPACE / 'verification/gravity_preparation/provisional_gravity.json'
OUTPUT = Path(__file__).parent / 'shoulder_dynamics.xml'
HOME = np.deg2rad([25, 65, 0, -25])
ZERO = np.zeros(4)
# User-confirmed simulation placement correction, 2026-11-01.
# Rotate the entire downstream J3 body at q3=0, including its inertial and J4.
# This is a fixed model transform, not a qpos target or a hardware encoder offset.
J3_PLACEMENT_OFFSET_RAD = np.pi


def numbers(values):
    return ' '.join(format(float(v), '.15g') for v in values)


def quaternion(rpy):
    q = Rotation.from_euler('xyz', rpy).as_quat()
    return numbers(q[[3, 0, 1, 2]])


def build():
    source = ET.parse(URDF).getroot()
    properties = json.loads(MASS.read_text(encoding='utf-8'))['links']
    root = ET.Element('mujoco', model='SLAI_shoulder_ESTIMATE_ONLY')
    root.append(ET.Comment('Generated by model.py from canonical URDF + provisional_gravity.json. '
        'SI units. Base Rx(-pi/2): +Y down; world gravity -Z. '
        'Simulation J3 fixed placement offset +pi about its local hinge axis. '
        'Hardware offsets, joint signs and numeric limits unchanged. '
        'Explicit CAD-derived provisional COM inertia, vendor mass scaling. '
        'No collision, no cable/payload, no motor rotor inertia/friction identification. '
        'Joint damping 0.05 is assumed, not measured. No real hardware interfaces. '
        'Do not use these gains or torques on hardware.'))
    ET.SubElement(root, 'compiler', angle='radian', inertiafromgeom='false')
    ET.SubElement(root, 'option', timestep='0.001', gravity='0 0 -9.80665', integrator='implicitfast')
    visual = ET.SubElement(root, 'visual')
    ET.SubElement(visual, 'global', offwidth='1200', offheight='800')
    asset = ET.SubElement(root, 'asset')
    mesh_assets = {}
    for link in source.findall('link'):
        name = link.get('name')
        filename = link.find('visual/geometry/mesh').get('filename').split('/')[-1]
        ET.SubElement(asset, 'mesh', name=name+'_mesh', file=filename)
        mesh_assets[filename] = (WORKSPACE / 'src/slaihand_description/meshes' / filename).read_bytes()
    world = ET.SubElement(root, 'worldbody')
    ET.SubElement(world, 'light', pos='0 -1 2', dir='0 0 -1', directional='true', ambient='.4 .4 .4')
    ET.SubElement(world, 'geom', name='visual_floor', type='plane', pos='0 0 -0.65',
                  size='2 2 .05', rgba='.16 .19 .23 1', contype='0', conaffinity='0')
    bodies = {'base_link': ET.SubElement(world, 'body', name='base_link',
                                       quat=quaternion([-np.pi/2, 0, 0]))}
    for joint in source.findall('joint'):
        origin = joint.find('origin')
        child = joint.find('child').get('link')
        parent = joint.find('parent').get('link')
        orientation = Rotation.from_euler('xyz', [float(v) for v in origin.get('rpy').split()])
        if joint.get('name') == 'slaihand_joint3':
            axis = np.asarray([float(v) for v in joint.find('axis').get('xyz').split()])
            orientation = orientation * Rotation.from_rotvec(
                axis / np.linalg.norm(axis) * J3_PLACEMENT_OFFSET_RAD)
        q = orientation.as_quat()
        body = ET.SubElement(bodies[parent], 'body', name=child,
            pos=origin.get('xyz'), quat=numbers(q[[3, 0, 1, 2]]))
        limit = joint.find('limit')
        ET.SubElement(body, 'joint', name=joint.get('name'), type='hinge',
                      axis=joint.find('axis').get('xyz'), limited='true',
                      range=limit.get('lower')+' '+limit.get('upper'), damping='.05')
        bodies[child] = body
    colors = {m.get('name'): m.find('color').get('rgba') for m in source.findall('material')}
    for link in source.findall('link'):
        name = link.get('name')
        body = bodies[name]
        p = properties[name]
        inertia = np.asarray(p['inertia_com_link_kg_m2'])
        eigen = np.linalg.eigvalsh(inertia)
        if min(eigen) <= 0 or max(eigen) > sum(eigen)-max(eigen)+1e-10:
            raise ValueError('Nonphysical provisional inertia: '+name)
        ET.SubElement(body, 'inertial', mass=str(p['mass_kg']), pos=numbers(p['com_link_m']),
            fullinertia=numbers([inertia[0,0], inertia[1,1], inertia[2,2],
                                inertia[0,1], inertia[0,2], inertia[1,2]]))
        ET.SubElement(body, 'geom', type='mesh', mesh=name+'_mesh', contype='0', conaffinity='0',
                      rgba=colors[link.find('visual/material').get('name')])
    ET.SubElement(bodies['link4'], 'site', name='link4_marker', size='.012', rgba='1 .3 .3 1')
    ET.indent(root)
    ET.ElementTree(root).write(OUTPUT, encoding='utf-8', xml_declaration=True)
    # MuJoCo native Windows path handling does not reliably accept Chinese paths.
    # Load the exact source meshes into the virtual file system, no duplicate mesh set.
    model = mujoco.MjModel.from_xml_string(ET.tostring(root, encoding='unicode'), assets=mesh_assets)
    if model.nq != 4 or model.nv != 4 or model.nu != 0:
        raise ValueError('Expected four simulated joints and no actuator/driver interface')
    return model


class Simulation:
    MODES = ('off', 'float', 'spring')
    # Demonstration gains and torque caps, NOT vendor motor ratings.
    KP = np.array([18., 14., 4., 3.])
    KD = np.array([3., 2., .5, .4])
    CAPS = np.array([30., 30., 10., 10.])

    def __init__(self, model=None):
        self.model = model if model is not None else build()
        self.data = mujoco.MjData(self.model)
        self.scratch = mujoco.MjData(self.model)
        self.mode = 'spring'
        self.target = ZERO.copy()
        self.torque = np.zeros(4)
        self.force_until = 0.
        self.force = np.zeros(3)
        self.body_id = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_BODY, 'link4')
        self.reset()

    def reset(self):
        """Reset simulation to confirmed joint zero, not the demonstration pose."""
        mujoco.mj_resetData(self.model, self.data)
        self.data.qpos[:] = ZERO
        self.target = ZERO.copy()
        self.torque[:] = 0
        self.force_until = 0.
        self.force[:] = 0
        mujoco.mj_forward(self.model, self.data)

    def enter_demo(self):
        """Simulation-only pose reset for comparison; does not redefine zero."""
        self.reset()
        self.data.qpos[:] = HOME
        self.target = HOME.copy()
        mujoco.mj_forward(self.model, self.data)

    def set_mode(self, mode):
        if mode not in self.MODES: raise ValueError('Unknown simulation mode')
        self.mode = mode

    def capture(self):
        self.target = np.clip(self.data.qpos.copy(), self.model.jnt_range[:,0], self.model.jnt_range[:,1])

    def push(self, force=(0,0,8), duration=.4):
        force = np.asarray(force, dtype=float)
        if force.shape != (3,) or not np.isfinite(force).all() or np.linalg.norm(force)>20:
            raise ValueError('Demo force must be finite and <=20 N')
        if not 0 < duration <= 1: raise ValueError('Demo pulse duration must be <=1 s')
        self.force[:] = force
        self.force_until = self.data.time + duration

    def gravity_torque(self):
        self.scratch.qpos[:] = self.data.qpos
        self.scratch.qvel[:] = 0
        mujoco.mj_forward(self.model, self.scratch)
        return self.scratch.qfrc_bias.copy()

    def step(self, count=1):
        for _ in range(count):
            torque = -self.KD * self.data.qvel
            if self.mode != 'off': torque += self.gravity_torque()
            if self.mode == 'spring': torque += self.KP * (self.target-self.data.qpos)
            self.torque = np.clip(torque, -self.CAPS, self.CAPS)
            self.data.qfrc_applied[:] = self.torque
            self.data.xfrc_applied[:] = 0
            if self.data.time < self.force_until:
                self.data.xfrc_applied[self.body_id,:3] = self.force
            mujoco.mj_step(self.model, self.data)
            if not np.isfinite(self.data.qpos).all() or not np.isfinite(self.data.qvel).all():
                raise RuntimeError('Nonfinite state: simulation stopped')
